// Builds site/demo/index.html from web/remote/index.html (the real phone app) so the demo never drifts:
// same markup, same CSS and app.js, plus a script that swaps the network for a simulated computer.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const site = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = fs.readFileSync(path.join(site, "..", "web", "remote", "index.html"), "utf8");
const html = source
  .replace('<link rel="manifest" href="manifest.webmanifest">', "")
  .replace('href="icon.svg"', 'href="../../web/remote/icon.svg"')
  .replace('<link rel="apple-touch-icon" href="icon.svg">', "")
  .replace('href="style.css"', 'href="../../web/remote/style.css"')
  .replace("<title>Vox Remote</title>", "<title>Vox · Live demo</title>")
  .replace('<script src="app.js" type="module"></script>', '<script type="module" src="../src/demo/demo-entry.js"></script>');
if (html.includes('src="app.js"')) throw new Error("make-demo: couldn't swap app.js; did web/remote/index.html change?");
fs.mkdirSync(path.join(site, "demo"), { recursive: true });
fs.writeFileSync(path.join(site, "demo", "index.html"), `<!-- GENERATED by site/scripts/make-demo.mjs from web/remote/index.html -->\n${html}`);
console.log("demo/index.html generated");
